#!/usr/bin/env bash
# Failure lab: genuine payments flow through Aegis while Aegis, Kafka and PostgreSQL are each killed
# (SIGKILL) and restarted. Afterwards every order the shop placed must be fulfilled exactly once:
# nothing acknowledged is lost, nothing is fulfilled twice. Writes lab/FAILURES.md; exits 1 otherwise.
#   lab/failures.sh               all three faults
#   FAULTS="aegis" lab/failures.sh
# Aegis delivers at least once (a delivery cut by a crash is sent again with the same ID); the shop
# fulfils an order once however often it hears of it, as every application behind Aegis must.
set -euo pipefail
cd "$(dirname "$0")/.."

if docker compose version >/dev/null 2>&1; then compose=(docker compose); else compose=(docker-compose); fi
compose+=(-f lab/compose.yaml -f lab/compose.failures.yaml)
faults=(${FAULTS:-aegis kafka postgres})
DOWN="${DOWN:-5}"          # seconds each component stays down
SETTLE="${SETTLE:-180}"    # seconds allowed for every order to be fulfilled after the last fault

./mvnw -q -B -ntp -DskipTests package -pl lab/mock-gateway,lab/vulnshop,aegis-service -am
"${compose[@]}" up -d --build --wait --quiet-pull >/dev/null
[[ "${KEEP:-}" == 1 ]] || trap '"${compose[@]}" down -v >/dev/null 2>&1' EXIT

export TARGET=aegis
# shellcheck source=attacks/lib.sh
source lab/attacks/lib.sh
flaws

work="$(mktemp -d)"
orders="$work/orders"
: >"$orders"

# The shop's customers keep paying throughout. An order Aegis cannot create (it is down) is an
# error the shop sees at once, and the customer simply tries again: only placed orders count.
traffic() {
  while [[ ! -f "$work/stop" ]]; do
    local placed shop gw r
    placed="$(order 49900 2>/dev/null)" || { sleep 0.2; continue; }
    read -r shop gw <<<"$placed"
    [[ -n "$gw" && "$gw" != null ]] || continue
    echo "$shop" >>"$orders"
    r="$(pay "{\"key_id\":\"$KEY_ID\",\"order_id\":\"$gw\"}" 2>/dev/null)" || continue
    curl -s -o /dev/null --max-time 5 -X POST "$(callback_url "$shop")" \
      --data-urlencode "razorpay_order_id=$(jq -r .razorpay_order_id <<<"$r")" \
      --data-urlencode "razorpay_payment_id=$(jq -r .razorpay_payment_id <<<"$r")" \
      --data-urlencode "razorpay_signature=$(jq -r .razorpay_signature <<<"$r")" || true
  done
}

traffic &
traffic_pid=$!
log=()
sleep "$DOWN"
for fault in "${faults[@]}"; do
  before="$(wc -l <"$orders" | tr -d ' ')"
  "${compose[@]}" kill -s SIGKILL "$fault" >/dev/null 2>&1
  sleep "$DOWN"
  "${compose[@]}" up -d --wait "$fault" >/dev/null 2>&1
  [[ "$fault" == aegis ]] || "${compose[@]}" up -d --wait aegis >/dev/null 2>&1
  log+=("$fault: killed after $before orders, down ${DOWN}s, restarted")
  echo "── ${log[${#log[@]}-1]}"
  sleep "$DOWN"
done
touch "$work/stop"
wait "$traffic_pid" || true

total="$(sort -u "$orders" | wc -l | tr -d ' ')"
echo "── $total orders placed; waiting up to ${SETTLE}s for every one to be fulfilled"
deadline=$((SECONDS + SETTLE))
while :; do
  once=0 missing=0 twice=0
  while read -r shop; do
    case "$(fulfilments "$shop")" in
      1) once=$((once + 1)) ;;
      0) missing=$((missing + 1)) ;;
      *) twice=$((twice + 1)) ;;
    esac
  done < <(sort -u "$orders")
  ((missing == 0 || SECONDS >= deadline)) && break
  sleep 5
done
waited=$((SETTLE - (deadline - SECONDS)))

result="failures $once/$total fulfilled exactly once ($missing missing, $twice more than once) after ${faults[*]}"
echo "$result"
{
  echo "# Failure lab results"
  echo
  echo "Generated by \`lab/failures.sh\`: genuine payments (webhook and browser callback each) through"
  echo "Aegis while each component is killed with SIGKILL and restarted. The gateway retries"
  echo "unacknowledged webhooks; Aegis delivers at least once; the shop fulfils an order once."
  echo
  echo "| Step | |"
  echo "|---|---|"
  for line in "${log[@]}"; do echo "| ${line%%:*} | ${line#*: } |"; done
  echo "| Result | **$once/$total** orders fulfilled exactly once, $missing missing, $twice more than once (settled within ${waited}s) |"
} >lab/FAILURES.md
echo "── written lab/FAILURES.md"
[[ $total -gt 0 && $once == "$total" ]]
