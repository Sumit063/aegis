#!/usr/bin/env bash
# Runs the Exploit Lab: builds the lab apps, starts them, runs every attack in every mode and
# writes lab/RESULTS.md. Exits 1 if any attack did not end as expected:
#   direct  → exploited (the flaw is real)
#   careful → blocked   (control: the same shop with the flaw off; the exploit needs that flaw)
#   aegis   → blocked   (the flawed shop behind Aegis)
#   lab/run.sh                 all modes in the compose file
#   KEEP=1 lab/run.sh          leave the containers running afterwards
set -euo pipefail
cd "$(dirname "$0")/.."

if docker compose version >/dev/null 2>&1; then compose=(docker compose); else compose=(docker-compose); fi
compose+=(-f lab/compose.yaml)
modes=(direct careful)
grep -q '^  aegis:' lab/compose.yaml && modes+=(aegis)

./mvnw -q -B -ntp -DskipTests package -pl lab/mock-gateway,lab/vulnshop,aegis-service -am
"${compose[@]}" up -d --build --wait --quiet-pull >/dev/null
[[ "${KEEP:-}" == 1 ]] || trap '"${compose[@]}" down -v >/dev/null 2>&1' EXIT

out_dir="$(mktemp -d)"
failed=0
for mode in "${modes[@]}"; do
  expected=$([[ $mode == direct ]] && echo exploited || echo blocked)
  echo "── $mode (expected: $expected)"
  for n in $(seq 1 10); do
    out="$(TARGET="$mode" "lab/attacks/F$n.sh" 2>&1 | tail -1)" || out="F$n error $out"
    echo "$out"
    echo "$out" >"$out_dir/$mode-F$n"
    [[ "$(awk '{print $2}' <<<"$out")" == "$expected" ]] || failed=1
  done
done

legit=""
if [[ " ${modes[*]} " == *" aegis "* ]]; then
  echo "── legitimate traffic through Aegis (expected: every order fulfilled exactly once)"
  if ! TARGET=aegis lab/attacks/legit.sh "${LEGIT:-100}" >"$out_dir/legit" 2>&1; then failed=1; fi
  legit="$(tail -1 "$out_dir/legit")"
  echo "$legit"
fi

{
  echo "# Exploit Lab results"
  echo
  echo "Generated by \`lab/run.sh\`. Each flaw is switched on alone in the reference shop (EXPLOIT-LAB §3)."
  echo
  header="| Flaw |"; rule="|---|"
  for mode in "${modes[@]}"; do header+=" $mode | What happened |"; rule+="---|---|"; done
  echo "$header"; echo "$rule"
  for n in $(seq 1 10); do
    row="| F$n |"
    for mode in "${modes[@]}"; do
      out="$(cat "$out_dir/$mode-F$n")"
      row+=" **$(awk '{print $2}' <<<"$out")** | $(sed -E 's/^[^ ]+ +[^ ]+ +//' <<<"$out") |"
    done
    echo "$row"
  done
  if [[ -n "$legit" ]]; then
    echo
    echo "**Legitimate traffic through Aegis:** ${legit#legit } (webhook + browser callback per payment, zero false blocks expected)."
  fi
} >lab/RESULTS.md

echo "── written lab/RESULTS.md"
exit "$failed"
